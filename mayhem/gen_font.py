#!/usr/bin/env python3
"""Emit default_font_bin.h (devkitPro's bin2s output, as a C array) from nx/data/default_font.bin."""
import sys
data = open(sys.argv[1], "rb").read()
with open(sys.argv[2], "w") as f:
    f.write("#pragma once\n/* generated by mayhem/gen_font.py from nx/data/default_font.bin */\n")
    f.write("static const unsigned char default_font_bin[%d] = {\n" % len(data))
    for i in range(0, len(data), 16):
        f.write("  " + ", ".join("0x%02x" % b for b in data[i:i + 16]) + ",\n")
    f.write("};\nstatic const unsigned int default_font_bin_size = %d;\n" % len(data))
